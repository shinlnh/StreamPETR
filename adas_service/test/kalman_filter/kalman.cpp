// Function to generate noisy signal data for both position and velocity
void generate_noisy_signals(const Eigen::VectorXf& time_steps, Eigen::MatrixXf& noisy_position, Eigen::MatrixXf& noisy_velocity) {
    std::default_random_engine generator;
    
    // Standard deviations for the noise
    float position_noise_std = 0.6;
    float velocity_noise_std = 0.6;
    
    std::normal_distribution<float> position_noise(0.0, position_noise_std);
    std::normal_distribution<float> velocity_noise(0.0, velocity_noise_std);

    for (int i = 0; i < time_steps.size(); ++i) {
        // Generate base sine and cosine signals for position and velocity
        float position = std::sin(time_steps(i));  // Simulating position
        float velocity = std::cos(time_steps(i));  // Simulating velocity

        // Add noise to simulate real-world signal
        noisy_position(i, 0) = (position + position_noise(generator))*10;
        noisy_velocity(i, 0) = (velocity + velocity_noise(generator))*10;
    }
}
